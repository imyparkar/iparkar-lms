// Regenerates src/lib/certificates/assets.generated.ts (base64) from src/lib/certificates/assets/.
// The Worker has no file system, so fonts and images are bundled as base64 like the invoice fonts.
import { readFileSync, writeFileSync } from "node:fs";
const dir = "src/lib/certificates/assets/";
const files = {
  interRegular: "Inter-Regular.ttf", interMedium: "Inter-Medium.ttf", interSemiBold: "Inter-SemiBold.ttf",
  interBold: "Inter-Bold.ttf", serifSemiBold: "SourceSerif4-Semibold.ttf", frauncesLight: "Fraunces-Light.ttf",
  talentTriangle: "talent-triangle.png", iconBA: "icon-business-acumen.png", iconWoW: "icon-ways-of-working.png", iconPS: "icon-power-skills.png",
};
let out = "/**\n * GENERATED by scripts/gen-certificate-assets.mjs — do not edit.\n * Certificate fonts (Inter, Source Serif 4, Fraunces Light: SIL Open Font License 1.1, latin subsets) and template images\n * from the design reference \"PMP certificate — A4 landscape\" (Talent Triangle artwork kept as supplied).\n */\n";
for (const [k, f] of Object.entries(files)) out += `export const ${k} = "${readFileSync(dir + f).toString("base64")}";\n`;
// The instructor's signature is NOT bundled (this repo is public): it is read from private R2 at issue time.
writeFileSync("src/lib/certificates/assets.generated.ts", out);
console.log("wrote", Object.keys(files).length, "assets,", Math.round(out.length / 1024), "KB");
